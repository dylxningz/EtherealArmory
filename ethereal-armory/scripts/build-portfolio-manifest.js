import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { buildPortfolioManifest } from "./lib/portfolioManifest.js";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const portfolioRoot = path.join(repositoryRoot, "public", "portfolio");
const outputPath = path.join(repositoryRoot, "src", "data", "portfolioManifest.generated.js");
const { projects, issues } = buildPortfolioManifest(portfolioRoot);

const output = `// Generated by npm run portfolio:manifest. Do not edit by hand.
export const portfolioProjects = Object.freeze(${JSON.stringify(projects, null, 2)});
`;

const previous = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : "";
if (previous !== output) fs.writeFileSync(outputPath, output, "utf8");

for (const issue of issues) {
  console.warn(`[portfolio] Excluded ${issue.project}: ${issue.message}`);
}
console.log(`[portfolio] Generated ${projects.length} publishable project${projects.length === 1 ? "" : "s"}; excluded ${issues.length}.`);
